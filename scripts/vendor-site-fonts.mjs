// Vendors the site's fonts completely: fetches the exact Google Fonts stylesheet URLs below with a modern
// browser User-Agent, downloads EVERY font file the stylesheets return, keeps font-weight and unicode-range,
// rewrites only src, and records a SHA-256 per file in site/src/fonts/manifest.json.
//   node scripts/vendor-site-fonts.mjs          download and write the manifest (needs network)
//   node scripts/vendor-site-fonts.mjs --check  verify files against the committed manifest (no network)
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dir = path.join(root, 'site', 'src', 'fonts');
const manifestPath = path.join(dir, 'manifest.json');
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/124.0 Safari/537.36';
const SOURCES = [
  { family: 'Roboto', url: 'https://fonts.googleapis.com/css2?family=Roboto:wght@400..700&display=swap' },
  { family: 'Roboto Mono', url: 'https://fonts.googleapis.com/css2?family=Roboto+Mono:wght@400..600&display=swap' },
];
const sha = (b) => crypto.createHash('sha256').update(b).digest('hex');

function check() {
  if (!fs.existsSync(manifestPath)) throw new Error('fonts manifest is missing: run node scripts/vendor-site-fonts.mjs');
  const m = JSON.parse(fs.readFileSync(manifestPath, 'utf8'));
  if (!m.files.length) throw new Error('fonts manifest lists no files');
  for (const f of m.files) {
    const p = path.join(dir, f.file);
    if (!fs.existsSync(p)) throw new Error('font file missing: ' + f.file);
    if (sha(fs.readFileSync(p)) !== f.sha256) throw new Error('font digest mismatch: ' + f.file);
  }
  if (!fs.existsSync(path.join(dir, 'fonts.css'))) throw new Error('fonts.css missing');
  return m;
}

if (process.argv.includes('--check')) {
  const m = check();
  console.log(`[fonts] ${m.files.length} files match the manifest`);
  process.exit(0);
}

fs.rmSync(dir, { recursive: true, force: true });
fs.mkdirSync(dir, { recursive: true });
const files = [];
let css = '/* Generated by scripts/vendor-site-fonts.mjs. Do not edit. */\n';
for (const s of SOURCES) {
  const res = await fetch(s.url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${s.url} answered ${res.status}`);
  const text = await res.text();
  const blocks = text.match(/(\/\*[^*]*\*\/\s*)?@font-face\s*\{[^}]*\}/g) || [];
  if (!blocks.length) throw new Error('no @font-face blocks for ' + s.url);
  for (const blk of blocks) {
    const subset = (blk.match(/\/\*\s*([^*]+?)\s*\*\//) || [])[1] || 'latin';
    const urlMatch = blk.match(/url\((https:[^)]+)\)/);
    if (!urlMatch) throw new Error('block without url in ' + s.url);
    const r = await fetch(urlMatch[1], { headers: { 'User-Agent': UA } });
    if (!r.ok) throw new Error(`${urlMatch[1]} answered ${r.status}`);
    const buf = Buffer.from(await r.arrayBuffer());
    const hash = sha(buf);
    const file = `${s.family.toLowerCase().replace(/\s+/g, '-')}-${subset.replace(/\s+/g, '-')}-${hash.slice(0, 8)}.woff2`;
    fs.writeFileSync(path.join(dir, file), buf);
    files.push({ family: s.family, subset, file, sha256: hash, bytes: buf.length, source: urlMatch[1] });
    css += blk.replace(/\/\*[^*]*\*\/\s*/, '').replace(/src:\s*url\([^)]+\)[^;]*;/, `src: url(${file}) format('woff2');`) + '\n';
  }
}
fs.writeFileSync(path.join(dir, 'fonts.css'), css);
fs.writeFileSync(manifestPath, JSON.stringify({ sources: SOURCES.map((s) => s.url), files }, null, 2) + '\n');
check();
console.log(`[fonts] vendored ${files.length} files`);
